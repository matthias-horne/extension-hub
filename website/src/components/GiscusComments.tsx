import { useEffect, useRef } from 'react';

const GISCUS_ORIGIN = 'https://giscus.app';
const DEFAULT_REPO = 'matthias-horne/extension-hub';
const DEFAULT_CATEGORY = 'General';

function giscusTheme() {
  return document.documentElement.classList.contains('dark') ? 'dark_dimmed' : 'light';
}

export function GiscusComments({ term }: { term: string }) {
  const container = useRef<HTMLDivElement>(null);
  const repo = import.meta.env.VITE_GISCUS_REPO?.trim() || DEFAULT_REPO;
  const repoId = import.meta.env.VITE_GISCUS_REPO_ID?.trim();
  const category = import.meta.env.VITE_GISCUS_CATEGORY?.trim() || DEFAULT_CATEGORY;
  const categoryId = import.meta.env.VITE_GISCUS_CATEGORY_ID?.trim();
  // Giscus requires the repository and category IDs generated by https://giscus.app.
  const enabled = Boolean(repoId && categoryId);

  useEffect(() => {
    if (!repoId || !categoryId || !container.current) return;
    const element = container.current;
    const script = document.createElement('script');
    script.src = GISCUS_ORIGIN + '/client.js';
    script.async = true;
    script.crossOrigin = 'anonymous';
    script.setAttribute('data-repo', repo);
    script.setAttribute('data-repo-id', repoId);
    script.setAttribute('data-category', category);
    script.setAttribute('data-category-id', categoryId);
    script.setAttribute('data-mapping', 'specific');
    script.setAttribute('data-term', term);
    script.setAttribute('data-strict', '1');
    script.setAttribute('data-reactions-enabled', '1');
    script.setAttribute('data-emit-metadata', '0');
    script.setAttribute('data-input-position', 'top');
    script.setAttribute('data-theme', giscusTheme());
    script.setAttribute('data-lang', 'en');
    script.setAttribute('data-loading', 'lazy');
    element.append(script);

    function syncTheme() {
      element.querySelector<HTMLIFrameElement>('iframe.giscus-frame')
        ?.contentWindow?.postMessage({ giscus: { setConfig: { theme: giscusTheme() } } }, GISCUS_ORIGIN);
    }

    const observer = new MutationObserver(syncTheme);
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['class'] });
    element.addEventListener('load', syncTheme, true);
    return () => {
      observer.disconnect();
      element.removeEventListener('load', syncTheme, true);
      element.replaceChildren();
    };
  }, [category, categoryId, repo, repoId, term]);

  if (!enabled) return null;

  const headingId = 'discussion-' + term;
  return (
    <div className="extension-discussion" role="region" aria-labelledby={headingId}>
      <h2 className="section-title" id={headingId}>Discuss this extension</h2>
      <p className="panel-description">Have a question or run into a problem? Ask the community below.</p>
      <div ref={container} className="giscus-comments" />
    </div>
  );
}
